#!/usr/bin/env python3
"""Generate HarfCore/Sources/Layout/KeyboardLayoutTables.swift from a real macOS layout dump.

The dump (scripts/data/macos-layouts.json) is produced on a macOS machine by
scripts/dump-layouts.swift, which asks UCKeyTranslate what each key types.

    python3 scripts/gen-layout-tables.py
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
dump = json.loads((root / "scripts/data/macos-layouts.json").read_text())
us = {r["key"]: r for r in dump["com.apple.keylayout.US"]}
DIGIT_KEYS = {18, 19, 20, 21, 22, 23, 25, 26, 28, 29}

def esc(s):
    return "".join(c if 32 < ord(c) < 127 and c not in '"\\' else "\\u{%04X}" % ord(c) for c in s)

def table(layout_id):
    rows = []
    for r in dump[layout_id]:
        k = r["key"]
        for level in ("plain", "shift"):
            latin, arabic = us[k][level], r[level]
            if not latin or not arabic or latin == arabic:
                continue
            rows.append((k, level, latin, arabic))
    return rows

out = ["// GENERATED by scripts/gen-layout-tables.py from a real macOS layout dump. Do not edit.",
       "// Source: UCKeyTranslate on macOS 26 (GitHub Actions runner), US vs Arabic layouts.",
       "",
       "extension KeyboardLayout {",
       "    /// One key position: what the US layout types and what this Arabic layout types.",
       "    struct KeyEntry: Sendable {",
       "        let keyCode: UInt16",
       "        let shifted: Bool",
       "        let latin: String",
       "        let arabic: String",
       "        let isDigitKey: Bool",
       "    }",
       ""]
for name, lid in (("apple", "com.apple.keylayout.Arabic"), ("pc", "com.apple.keylayout.ArabicPC")):
    out.append(f"    /// `{lid}`")
    out.append(f"    static let {name}Entries: [KeyEntry] = [")
    for k, level, latin, arabic in table(lid):
        out.append(f'        KeyEntry(keyCode: {k}, shifted: {"true" if level=="shift" else "false"}, '
                   f'latin: "{esc(latin)}", arabic: "{esc(arabic)}", isDigitKey: {"true" if (k in DIGIT_KEYS and level=="plain") else "false"}),')
    out.append("    ]")
    out.append("")
out.append("}")
(root / "HarfCore/Sources/Layout/KeyboardLayoutTables.swift").write_text("\n".join(out) + "\n")
print("ok")
