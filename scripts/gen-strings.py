root = pathlib.Path(__file__).resolve().parent.parent
used = set()
for f in glob.glob(str(root / "HarfApp/**/*.swift"), recursive=True):
    s = open(f, encoding="utf-8").read()
    for pat in [r'loc\("((?:[^"\\]|\\.)*)"\)', r'loc\.format\("((?:[^"\\]|\\.)*)"', r'(?:key|titleKey): "((?:[^"\\]|\\.)*)"']:
        used.update(re.findall(pat, s))
    if f.endswith(("Localization.swift", "HotKeyCenter.swift")):
        for k in re.findall(r'return "((?:[^"\\]|\\.)*)"', s):
            if " " in k or k[:1].isupper() or not k.isascii():
                used.add(k)
used |= {"Arabic", "Arabic - PC"}
missing = sorted(k for k in used if k not in AR and k not in {"Space"})
if missing:
    print("Missing Arabic translations:", *missing, sep="\n  ")
    sys.exit(1)

strings = {}
for key in sorted(AR):
    strings[key] = {"localizations": {
        "en": {"stringUnit": {"state": "translated", "value": key}},
        "ar": {"stringUnit": {"state": "translated", "value": AR[key]}},
    }}
catalog = {"sourceLanguage": "en", "strings": strings, "version": "1.0"}
out = root / "HarfApp/Resources/Localizable.xcstrings"
out.write_text(json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
print(f"{len(strings)} strings written, {len(used)} keys used")
